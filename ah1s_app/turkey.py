def bounds():
    xs = [p[0] for p in ANATOLIA + THRACE]
    ys = [p[1] for p in ANATOLIA + THRACE]
    return min(xs), max(xs), min(ys), max(ys)


class MapProjection:
    """(boylam, enlem) → piksel; haritayı verilen dikdörtgene oranını koruyarak sığdırır."""

    def __init__(self, rect, pad: float = 16.0):
        x0, x1, y0, y1 = bounds()
        w, h = (x1 - x0) * _K, (y1 - y0)
        self.s = min((rect.width - 2 * pad) / w, (rect.height - 2 * pad) / h)
        self.ox = rect.centerx - (x0 + x1) / 2 * _K * self.s
        self.oy = rect.centery + (y0 + y1) / 2 * self.s

    def __call__(self, lon: float, lat: float) -> tuple[float, float]:
        return self.ox + lon * _K * self.s, self.oy - lat * self.s
